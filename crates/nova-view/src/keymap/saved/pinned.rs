#[test]
fn every_default_combo_saves_as_its_pinned_text_and_parses_back() {
    let map = KeyMap::default();
    let defaults: Vec<(Command, KeyCombo)> = Command::all()
        .filter_map(|command| map.combo(command).map(|combo| (command, combo)))
        .collect();
    assert_eq!(
        defaults.len(),
        PINNED.len(),
        "every command with a default combo is pinned"
    );
    for &(name, text) in PINNED {
        let command = Command::from_name(name).unwrap_or_else(|| panic!("{name} names a command"));
        let combo = map
            .combo(command)
            .unwrap_or_else(|| panic!("{name} has a default"));
        assert_eq!(combo.to_string(), text, "{name}");
        assert_eq!(text.parse::<KeyCombo>(), Ok(combo), "{name}");
    }
}
